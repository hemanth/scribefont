def get_glyph_strokes(ch: str) -> list[list[tuple[float, float]]]:
    return GLYPH_STROKES.get(ch, GLYPH_STROKES["A"])


def resample_polyline(pts: list[tuple[float, float]], target_n: int) -> list[tuple[float, float]]:
    if len(pts) == 1:
        return [pts[0] for _ in range(target_n)]
    dists = [0.0]
    for i in range(1, len(pts)):
        d = math.hypot(pts[i][0] - pts[i - 1][0], pts[i][1] - pts[i - 1][1])
        dists.append(dists[-1] + max(1e-6, d))
    total = dists[-1]
    out: list[tuple[float, float]] = []
    for k in range(target_n):
        target_d = (k / max(1, target_n - 1)) * total
        idx = 0
        while idx < len(dists) - 2 and dists[idx + 1] < target_d:
            idx += 1
        seg_len = max(1e-6, dists[idx + 1] - dists[idx])
        t = max(0.0, min(1.0, (target_d - dists[idx]) / seg_len))
        x = pts[idx][0] + t * (pts[idx + 1][0] - pts[idx][0])
        y = pts[idx][1] + t * (pts[idx + 1][1] - pts[idx][1])
        out.append((round(x, 5), round(y, 5)))
    return out


def canonical_skeleton_points(ch: str) -> list[tuple[float, float]]:
    """Flatten the character's real multi-stroke trajectory into 16 canonical keypoints for the neural transformer."""
    strokes = get_glyph_strokes(ch)
    n_strokes = len(strokes)
    if n_strokes == 1:
        return resample_polyline(strokes[0], 16)
    elif n_strokes == 2:
        p1 = resample_polyline(strokes[0], 10)
        p2 = resample_polyline(strokes[1], 6)
        return p1 + p2
    else:
        p1 = resample_polyline(strokes[0], 6)
        p2 = resample_polyline(strokes[1], 5)
        p3 = resample_polyline(strokes[2], 5)
        return p1 + p2 + p3


def split_16pts_into_strokes(ch: str, pts_16: list[list[float]] | list[tuple[float, float]]) -> list[list[list[float]]]:
    """Re-partition 16 predicted keypoints back into the character's open stroke polylines."""
    strokes = get_glyph_strokes(ch)
    n_strokes = len(strokes)
    pts = [[float(p[0]), float(p[1])] for p in pts_16]
    if n_strokes == 1:
        return [pts]
    elif n_strokes == 2:
        return [pts[:10], pts[10:16]]
    else:
        return [pts[:6], pts[6:11], pts[11:16]]
